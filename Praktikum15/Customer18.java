package Praktikum15;

public class Customer18 {
    public int id;
    public String name;
    public Customer18() {
    }
 
    public Customer18(int id, String name) {
        this.id = id;
        this.name = name;
    }

    
    public String toString() {
        return " ID: " + this.id + " Nama: " + this.name;
    }
}
